function pageTsx(ctx) {
  return `// ${ctx.pascal} — Page scaffold (Card + Table + error Alert + loading). Generated by
// gen-feature ${ctx.date}. The sample calls GET /api/${ctx.name} — change api/${ctx.name}.ts
// to the real contract (contract-first: edit the OpenAPI spec first for new services).
import { useCallback, useEffect, useState } from 'react';
import { Alert, Button, Card, Table, type TableColumn } from '@wakii/ui-kit';
import { ApiError, list${ctx.pascal}s, type ${ctx.pascal}Row } from '../api/${ctx.name}.js';

type LoadState = 'loading' | 'error' | 'ready';

const columns: TableColumn<${ctx.pascal}Row>[] = [
  { key: 'id', title: 'ID', width: '200px' },
  { key: 'name', title: 'Name' },
  { key: 'createdAt', title: 'Created at', width: '200px' },
];

export function ${ctx.pascal}() {
  const [rows, setRows] = useState<${ctx.pascal}Row[]>([]);
  const [state, setState] = useState<LoadState>('loading');
  const [errText, setErrText] = useState('');

  const load = useCallback(async () => {
    setState('loading');
    try {
      const data = await list${ctx.pascal}s();
      setRows(data.items);
      setState('ready');
    } catch (err) {
      setErrText(err instanceof ApiError ? err.code + ': ' + err.message : String(err));
      setState('error');
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  return (
    <Card
      title="${ctx.pascal}"
      extra={
        <Button size="small" onClick={() => void load()} loading={state === 'loading'}>
          Reload
        </Button>
      }
    >
      {state === 'error' && (
        <Alert
          type="warning"
          message="Failed to load data"
          description={errText + ' — check that the /api/${ctx.name} service exists (BE) or that a token is present (auth).'}
        />
      )}
      <Table<${ctx.pascal}Row>
        columns={columns}
        dataSource={rows}
        rowKey="id"
        striped
        size="small"
        loading={state === 'loading'}
      />
    </Card>
  );
}
`;
}

function pageTestTsx(ctx) {
  return `// ${ctx.pascal} smoke — mocked fetch: ok renders rows, failure shows the Alert (envelope decode).
import { cleanup, render, screen, waitFor } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { ${ctx.pascal} } from './${ctx.pascal}.js';

afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
});

describe('${ctx.pascal}', () => {
  it('fetch ok → renders rows in the Table', async () => {
    vi.stubGlobal(
      'fetch',
      vi.fn(async () =>
        new Response(JSON.stringify({ items: [{ id: 'r-1', name: 'real row', createdAt: '2026-01-01T00:00:00Z' }], total: 1 }), {
          status: 200,
        }),
      ),
    );
    render(<${ctx.pascal} />);
    await waitFor(() => expect(screen.getByText('real row')).toBeInTheDocument());
  });

  it('fetch fail → error Alert (no crash)', async () => {
    vi.stubGlobal(
      'fetch',
      vi.fn(async () =>
        new Response(JSON.stringify({ error: { code: 'UNAUTHORIZED', message: 'Missing token', requestId: null, details: null } }), {
          status: 401,
        }),
      ),
    );
    render(<${ctx.pascal} />);
    await waitFor(() => expect(screen.getByText(/Failed to load data/)).toBeInTheDocument());
    expect(screen.getByText(/UNAUTHORIZED/)).toBeInTheDocument();
  });
});
`;
}

