// docinsert.mjs — insertions/removals in "lightly structured text" that is neither
// yaml nor nginx: markdown table rows (conventions/05), JSX routes in App.tsx
// (gen-feature), rspack exposes entries. Every function looks for a STABLE anchor
// specific to the boilerplate; not found → null (the caller adds a next_step with
// manual instructions — it never guesses).

/**
 * Add a row to the port table of platform/conventions/05-ports.md — right after the
 * postgres row (currently the last table row). Anchor missing → null → next_step.
 */
export function appendPortsTableRow(text, name, port, note) {
  const anchor = '| postgres | 5432 | Postgres 16 |';
  if (!text.includes(anchor)) return null;
  return text.replace(anchor + '\n', `${anchor}\n| ${name} | ${port} | ${note} |\n`);
}

/**
 * Remove the port-table row whose first cell is exactly `name` (generated rows only —
 * we never touch rows we did not generate). Returns the new text; row absent → text unchanged.
 */
export function removePortsTableRow(text, name) {
  const re = new RegExp(`^\\| ${name} \\| \\d+ \\|[^|]*\\|\\n`, 'm');
  return text.replace(re, '');
}

/**
 * Insert a route + Page import into a react-router declarative App.tsx
 * (shell + admin + generated SPAs all use `<Routes>`).
 * Prefers the JSX comment marker "GEN:routes" (apps generated by gen-app carry it);
 * fallback inserts BEFORE the catch-all `<Route path="*"` line (line start — keeps
 * the original indentation). Neither found → null (caller writes files + manual
 * instructions). Throws when the route already exists (idempotent-guard).
 */
export function insertAppRoute(text, { routePath, componentName, importLine }) {
  if (text.includes(`path="${routePath}"`)) {
    throw new Error(`route "${routePath}" already exists in App.tsx — idempotent-guard`);
  }
  const marker = '{' + '/* GEN:routes */}';
  const hasMarker = text.includes(marker);
  const catchAllIdx = text.indexOf('<Route path="*"');
  if (!hasMarker && catchAllIdx === -1) return null;

  const withImport = appendImport(text, importLine);
  const routeEl = `        <Route path="${routePath}" element={<${componentName} />} />\n`;
  if (hasMarker) {
    const idx = withImport.indexOf(marker) + marker.length;
    return withImport.slice(0, idx) + '\n' + routeEl + withImport.slice(idx);
  }
  const tokenAt = withImport.indexOf('<Route path="*"');
  const lineStart = withImport.lastIndexOf('\n', tokenAt) + 1;
  return withImport.slice(0, lineStart) + routeEl + withImport.slice(lineStart);
}

/**
 * Remove the route line for `routePath` + the matching Page import line (generated
 * lines only — matched by exact component name). Route absent → text unchanged.
 */
export function removeAppRoute(text, { routePath, componentName }) {
  let out = text.replace(new RegExp(`^\\s*<Route path="${routePath}" element=\\{<${componentName} />\\} />\\n`, 'm'), '');
  out = out.replace(new RegExp(`^import \\{ ${componentName} \\} from '[^']*';\\n`, 'm'), '');
  return out;
}

/** Add an import line after the last `import ...` line of the file (top import block). */
export function appendImport(text, importLine) {
  const lines = text.split('\n');
  let last = -1;
  for (let i = 0; i < lines.length; i++) {
    if (/^import /.test(lines[i])) last = i;
  }
  if (last === -1) return `${importLine}\n${text}`;
  lines.splice(last + 1, 0, importLine);
  return lines.join('\n');
}

/**
 * Add an exposes entry to a remote's rspack.config.mjs (gen-feature on an MF app
 * without a router): anchor `exposes: {` — inserted with the existing entry indent.
 * Anchor missing → null.
 */
export function insertRspackExpose(text, { exposedModule, file }) {
  if (text.includes(`'${exposedModule}'`)) {
    throw new Error(`rspack exposes already has '${exposedModule}' — idempotent-guard`);
  }
  const anchor = 'exposes: {';
  const idx = text.indexOf(anchor);
  if (idx === -1) return null;
  const lineEnd = text.indexOf('\n', idx);
  const firstEntry = text.slice(lineEnd + 1);
  const indentMatch = firstEntry.match(/^[ \t]*/);
  const indent = indentMatch ? indentMatch[0] : '      ';
  const entry = `\n${indent}'${exposedModule}': '${file}',`;
  return text.slice(0, lineEnd) + entry + text.slice(lineEnd);
}

/** Remove an exposes entry (exact generated line). Absent → text unchanged. */
export function removeRspackExpose(text, exposedModule) {
  const re = new RegExp(`^\\s*'${exposedModule}': '[^']*',\\n`, 'm');
  return text.replace(re, '');
}

/**
 * Add an item to a `NAV_ITEMS` array (shell NavBar pattern):
 *   const NAV_ITEMS = [ { to: '/', label: '…' }, … ] as const;
 * Inserts before the array's closing `]`, indent copied from the last item
 * (flat array — items are single-line). Anchor missing → null (caller adds a
 * next_step with manual instructions). Existing path → throws (idempotent-guard).
 */
export function insertNavItem(text, { to, label }) {
  if (new RegExp(`to: '${to.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}'`).test(text)) {
    throw new Error(`nav already has an item for '${to}' — idempotent-guard`);
  }
  const declIdx = text.indexOf('NAV_ITEMS');
  if (declIdx === -1) return null;
  const openIdx = text.indexOf('[', declIdx);
  if (openIdx === -1) return null;
  const closeIdx = text.indexOf(']', openIdx);
  if (closeIdx === -1) return null;
  const before = text.slice(openIdx + 1, closeIdx);
  let indent = '  ';
  const lastItem = before.lastIndexOf('{');
  if (lastItem !== -1) {
    const lineStart = text.lastIndexOf('\n', openIdx + 1 + lastItem) + 1;
    indent = text.slice(lineStart).match(/^[ \t]*/)?.[0] ?? '  ';
  }
  const entry = `${before.endsWith('\n') ? '' : '\n'}${indent}{ to: '${to}', label: '${label}' },\n`;
  return text.slice(0, closeIdx) + entry + text.slice(closeIdx);
}
