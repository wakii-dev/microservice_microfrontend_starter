function inMemoryStoreJava(ctx) {
  return (
    `package ` +
    ctx.pkg +
    `.service;

import java.time.Instant;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import org.springframework.stereotype.Component;

/**
 * In-memory ItemStore used when the service has no database yet (same shape as
 * the TS template's repo.memory). Newest-first by createdAt; patches never
 * reorder. When a database lands (--db), swap for JpaItemStore + Flyway.
 */
@Component
public class InMemoryItemStore implements ItemStore {

    private final Map<UUID, Item> store = new ConcurrentHashMap<>();

    @Override
    public ItemPage list(int limit, int offset) {
        List<Item> all = store.values().stream()
                .sorted(Comparator.comparing(Item::createdAt).reversed().thenComparing(Item::id))
                .toList();
        return new ItemPage(all.stream().skip(offset).limit(limit).toList(), all.size());
    }

    @Override
    public Optional<Item> get(UUID id) {
        return Optional.ofNullable(store.get(id));
    }

    @Override
    public Item create(String name) {
        Instant now = Instant.now();
        Item item = new Item(UUID.randomUUID(), name, now, now);
        store.put(item.id(), item);
        return item;
    }

    @Override
    public Optional<Item> update(UUID id, String name) {
        return Optional.ofNullable(store.computeIfPresent(id, (k, item) ->
                new Item(item.id(), name, item.createdAt(), Instant.now())));
    }

    @Override
    public boolean delete(UUID id) {
        return store.remove(id) != null;
    }

    /** Test convenience — clean state between tests (no transaction rollback without a DB). */
    public void clear() {
        store.clear();
    }
}
`
  );
}

