#!/usr/bin/env node
// remove-service.mjs — `pnpm remove:service <name>`
// The INVERSE of gen:service: removes services/<name>/ plus every generated wiring —
// compose block (with gateway depends_on + postgres env keys), gateway nginx location
// (inside the GEN:services markers), .env.example keys, pnpm-workspace.yaml entry,
// the conventions/05 port row, the postgres init script, the contract spec, the CI
// workflow, and the stack manifest entry.
// Idempotent: pieces already gone are skipped; nothing left → removed: [] + a note.
// Guards: DEFAULT services are REFUSED (they are boilerplate infrastructure).
// Output contract for AI: --json → {created, removed, modified, next_steps}.
import path from 'node:path';
import { composeHasService, removeComposeService, removeWorkspacePackage } from './lib/compose-yaml.mjs';
import { removePortsTableRow } from './lib/docinsert.mjs';
import { removeEnvKeys } from './lib/envfile.mjs';
import { exists, isDir, readText, removeTree, writeText } from './lib/io.mjs';
import { removeManifestService } from './lib/manifest.mjs';
import { removeApiLocation } from './lib/nginx.mjs';
import { parseArgs, requireValidName, screaming } from './lib/naming.mjs';
import { emit, emitError, helpText, GenResult } from './lib/result.mjs';

const HELP = helpText({
  usage: 'usage: pnpm remove:service <name> [--root <dir>] [--json] [--help]',
  summary:
    'Remove a GENERATED service and all of its wiring (compose, gateway location, env keys, workspace entry, ' +
    'port-table row, postgres init script, contract spec, CI workflow, stack manifest entry). ' +
    'Default/infrastructure services are REFUSED. Idempotent: already-removed pieces are skipped.',
  flags: [
    '<name>          kebab-case service name (required, first positional)',
    '--root <dir>    repo root (default: cwd)',
    '--json          output JSON {created, removed, modified, next_steps} — AI contract',
    '--help          this page',
  ],
  examples: ['pnpm remove:service notification-svc', 'pnpm remove:service notification-svc --json'],
  refs: [
    'Inverse of pnpm gen:service — anything NOT generated by gen:service is left untouched.',
    'Default services (postgres, kafka, gateway, node-svc, spring-svc, go-svc, auth-svc, dotnet-svc, shell, remote-*) are protected.',
  ],
});

/** Services the boilerplate cannot live without — remove:service refuses them. */
const PROTECTED_SERVICES = new Set([
  'postgres',
  'kafka',
  'gateway',
  'shell',
  'node-svc',
  'spring-svc',
  'go-svc',
  'auth-svc',
  'dotnet-svc',
  'admin',
]);

export function parseAndValidate(argv) {
  const { flags, positionals } = parseArgs(argv);
  const name = positionals[0];
  if (!name || flags.help) return { help: true };
  requireValidName(name, 'service name');
  if (PROTECTED_SERVICES.has(name)) {
    throw new Error(`"${name}" is a default/infrastructure service — remove:service refuses it`);
  }
  if (name.startsWith('remote-')) {
    throw new Error(`"${name}" looks like an MF remote app (remove with gen-app's inverse or manually) — remove:service refuses remote-* names`);
  }
  return { help: false, name, root: flags.root ?? process.cwd(), json: flags.json === true };
}

export function runRemoveService(opts) {
  const { name } = opts;
  const root = opts.root;
  const res = new GenResult();
  const scream = screaming(name);

  const composePath = path.join(root, 'platform/docker-compose.yml');
  const nginxPath = path.join(root, 'platform/gateway/nginx/nginx.conf');
  const envPath = path.join(root, 'platform/.env.example');
  const workspacePath = path.join(root, 'pnpm-workspace.yaml');
  const portsDocPath = path.join(root, 'platform/conventions/05-ports.md');
  const manifestPath = path.join(root, 'app/stack-template/stack-manifest.json');
  const svcDir = path.join(root, 'services', name);
  const contractPath = path.join(root, 'contracts/openapi', `${name}.yaml`);
  const workflowPath = path.join(root, '.github/workflows', `services-${name}.yml`);
  const initScriptPath = path.join(root, 'platform/postgres/init', `02-${name}.sh`);

  for (const p of [composePath, nginxPath, envPath]) {
    if (!exists(p)) {
      throw new Error(`not the boilerplate repo — missing ${path.relative(root, p)} (run from the repo root or pass --root <dir>)`);
    }
  }

  // Collect the db-related env keys to purge from compose/.env (shared + dedicated variants).
  const envKeys = [`${scream}_PORT`, `${scream}_DB_PASSWORD`, `POSTGRES_${scream}_DB`, `POSTGRES_${scream}_USER`];
  const postgresEnvKeys = [`${scream}_DB_PASSWORD`, `POSTGRES_${scream}_DB`, `POSTGRES_${scream}_USER`, `POSTGRES_${scream}_DB_PASSWORD`];

  // --- dir ---
  if (isDir(svcDir)) {
    removeTree(svcDir);
    res.removedItem(`services/${name}/`);
  }

  // --- compose block + gateway depends_on + postgres env keys ---
  const composeText = readText(composePath);
  if (composeHasService(composeText, name)) {
    const newCompose = removeComposeService(composeText, name, { host: 'gateway', postgresEnvKeys });
    writeText(composePath, newCompose);
    res.removedItem(`compose service "${name}"`);
    res.modifiedFile('platform/docker-compose.yml');
  }

  // --- nginx location (inside the GEN:services markers only) ---
  const nginxRes = removeApiLocation(readText(nginxPath), name);
  if (nginxRes.removed) {
    writeText(nginxPath, nginxRes.text);
    res.removedItem(`nginx location /api/${name}`);
    res.modifiedFile('platform/gateway/nginx/nginx.conf');
  }

  // --- .env.example keys + generated section ---
  const envRes = removeEnvKeys(envPath, { header: `gen: ${name}`, keys: envKeys });
  if (envRes.removed.length > 0) {
    res.removedItem(`.env.example keys: ${envRes.removed.join(', ')}`);
    res.modifiedFile('platform/.env.example');
  }

  // --- pnpm-workspace entry (TS services only; absent → skip) ---
  if (exists(workspacePath)) {
    const before = readText(workspacePath);
    const after = removeWorkspacePackage(before, `services/${name}`);
    if (after !== before) {
      writeText(workspacePath, after);
      res.removedItem(`pnpm-workspace.yaml entry services/${name}`);
      res.modifiedFile('pnpm-workspace.yaml');
    }
  }

  // --- conventions/05 port row ---
  if (exists(portsDocPath)) {
    const before = readText(portsDocPath);
    const after = removePortsTableRow(before, name);
    if (after !== before) {
      writeText(portsDocPath, after);
      res.removedItem(`conventions/05 port row ${name}`);
      res.modifiedFile('platform/conventions/05-ports.md');
    }
  }

  // --- postgres init script ---
  if (exists(initScriptPath)) {
    removeTree(initScriptPath);
    res.removedItem(`platform/postgres/init/02-${name}.sh`);
  }

  // --- contract spec ---
  if (exists(contractPath)) {
    removeTree(contractPath);
    res.removedItem(`contracts/openapi/${name}.yaml`);
  }

  // --- CI workflow ---
  if (exists(workflowPath)) {
    removeTree(workflowPath);
    res.removedItem(`.github/workflows/services-${name}.yml`);
  }

  // --- stack manifest entry ---
  if (exists(manifestPath)) {
    if (removeManifestService(manifestPath, name)) {
      res.removedItem(`stack manifest entry "${name}"`);
      res.modifiedFile('app/stack-template/stack-manifest.json');
    }
  }

  // --- idempotency note ---
  if (res.toJSON().removed.length === 0) {
    res.next(`service "${name}" was not found anywhere (dir, compose, nginx, env, manifest) — nothing to remove`);
  } else {
    res.next(
      'run: pnpm install  # drop the removed workspace importer from pnpm-lock.yaml (CI --frozen-lockfile needs the refreshed lock)',
      `verify: docker compose -f platform/docker-compose.yml --env-file platform/.env.example config -q  # compose still VALID`,
      'note: if the service had a database, dropping its volume needs docker compose down -v (destroys other services data too — CLAUDE.md gotchas)',
    );
  }
  return res;
}

// --- CLI entry ---
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.length === 0) {
  process.stdout.write(HELP + '\n');
  process.exit(0);
}
try {
  const opts = parseAndValidate(argv);
  if (opts.help) {
    process.stdout.write(HELP + '\n');
    process.exit(0);
  }
  emit(runRemoveService(opts), { json: opts.json });
} catch (err) {
  emitError(err, { json: argv.includes('--json') });
  process.exit(1);
}
