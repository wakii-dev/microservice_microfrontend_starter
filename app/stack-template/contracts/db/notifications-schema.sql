CREATE SCHEMA IF NOT EXISTS notifications;

CREATE TABLE IF NOT EXISTS notifications.notifications (
    id         uuid PRIMARY KEY,
    user_id    uuid NOT NULL,
    title      varchar(200) NOT NULL,
    body       text,
    read       boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_notifications_user_id    ON notifications.notifications (user_id);
CREATE INDEX IF NOT EXISTS idx_notifications_created_at ON notifications.notifications (created_at DESC);

-- ----------------------------------------------------------------------------
-- Design decisions (do NOT "helpfully" change):
--
-- 1. user_id has NO FK into schema `users`/`auth`: users belong to another
--    service (spring/auth) — cross-schema FKs create migration coupling between
--    independent services (mirror of tasks-schema.sql decision #1). Integrity is
--    enforced at the application level: every query filters WHERE user_id = JWT
--    sub — a user sees only their own notifications; no API accepts a userId
--    from the client.
--
-- 2. `read` is a NON-RESERVED keyword in PostgreSQL — usable as a column name
--    without quoting; 1:1 with field `read` in contracts/openapi/dotnet.yaml.
--
-- 3. id generated by the app (uuid v4) — no DEFAULT gen_random_uuid() (mirror
--    tasks-schema.sql #3 — no pgcrypto extension needed).
