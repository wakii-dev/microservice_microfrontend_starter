function rspackConfig(ctx) {
  return `import { ModuleFederationPlugin } from '@module-federation/enhanced/rspack';
import { DefinePlugin, HtmlRspackPlugin } from '@rspack/core';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Windows-safe absolute path (URL.pathname yields /C:/... which is wrong on win32)
const rootDir = path.dirname(fileURLToPath(import.meta.url));

/**
 * Remote \`${ctx.name}\` — MF REMOTE (generated ${ctx.date} — gen-app --remote, the app/remotes/tasks pattern).
 * Exposes ./${ctx.pascal}Page — loaded into a shell slot (registry conventions/08; RENAMING
 * the name/expose is breaking — sync conventions/08 + shell). Dev port ${ctx.port} (conventions/05).
 * Pin matrix per app/shared mfToolkit (react 19.3.0 / rspack 1.7.12 / mf-enhanced 0.21.6
 * — upgrades require a re-spike through app/spike).
 *
 * Build-time env (conventions/06 — no hardcoding):
 *   API_BASE_URL — API base. Dev native: '' + the dev-server /api proxy (below).
 *     Prod (via gateway): '' (same-origin).
 *   REMOTE_PUBLIC_PATH — chunk publicPath. Dev: http://localhost:${ctx.port}/ ;
 *     Prod: /remotes/${ctx.name}/ (relative via the gateway, conventions/08).
 */
const isDev = process.env.NODE_ENV !== 'production';

const apiBaseUrl = process.env.API_BASE_URL ?? '';
const publicPath = process.env.REMOTE_PUBLIC_PATH || (isDev ? 'http://localhost:${ctx.port}/' : '/remotes/${ctx.name}/');

export default {
  // 2 entries (BUG-1 sf-5b — the tasks pattern): \`index\` = async boundary for the MF
  // container (remoteEntry.js — RUNTIME-006: a static shared entry → loadShareSync
  // before share init → crash in-shell); \`standalone\` = STATIC entry for the :${ctx.port}
  // debug page — the whole graph bundles synchronously, no async shared chunks.
  // index.html only injects \`standalone\`.
  entry: {
    index: './src/index.tsx',
    standalone: './src/standalone.tsx',
  },
  output: {
    publicPath,
    filename: isDev ? '[name].js' : '[name].[contenthash].js',
    cssFilename: isDev ? '[name].css' : '[name].[contenthash].css',
    clean: true,
  },
  resolve: {
    extensions: ['.tsx', '.ts', '.jsx', '.js'],
    // fe-shared (READ-ONLY) imports NodeNext-style: './x.js' points at a .ts file
    extensionAlias: {
      '.js': ['.ts', '.tsx', '.js'],
    },
    // fe-shared src/ui imports 'react' but the package does not declare it — resolve
    // through the consumer's node_modules (the tasks pattern — one runtime singleton).
    modules: [path.resolve(rootDir, 'node_modules'), 'node_modules'],
  },
  module: {
    rules: [
      {
        test: /\\.css$/,
        // Tailwind v4 via postcss — mirrors shell/tasks
        type: 'css',
        use: [
          {
            loader: 'postcss-loader',
            options: {
              postcssOptions: {
                plugins: { '@tailwindcss/postcss': {} },
              },
            },
          },
        ],
      },
      {
        test: /\\.tsx?$/,
        // fe-shared is a raw TS package (main: ./src/index.ts) — the bundler compiles it too
        include: [path.resolve(rootDir, 'src'), /[\\\\/]app[\\\\/](shared|ui-kit)[\\\\/]src/],
        use: {
          loader: 'builtin:swc-loader',
          options: {
            jsc: {
              parser: { syntax: 'typescript', tsx: true },
              transform: { react: { runtime: 'automatic' } },
              target: 'es2022',
            },
          },
        },
        type: 'javascript/auto',
      },
    ],
  },
  plugins: [
    // index.html is only for the standalone debug page (:${ctx.port}) — injects ONLY the standalone entry
    new HtmlRspackPlugin({
      template: './index.html',
      chunks: ['standalone'],
    }),
    new DefinePlugin({
      __API_BASE_URL__: JSON.stringify(apiBaseUrl),
    }),
    new ModuleFederationPlugin({
      name: '${ctx.name}',
      filename: 'remoteEntry.js',
      exposes: {
        './${ctx.pascal}Page': './src/${ctx.pascal}Page.tsx',
      },
      // Singletons per the pin matrix — requiredVersion: false ("catalog:" deps confuse
      // mf-enhanced's inference); eager: true (BUG-1 sf-5b — stale prod chunk ids). Tasks pattern.
      shared: {
        react: { singleton: true, requiredVersion: false, eager: true },
        'react-dom': { singleton: true, requiredVersion: false, eager: true },
        'react/jsx-runtime': { singleton: true, requiredVersion: false, eager: true },
        // MUST be shared symmetrically with the shell — missing it splits the context from
        // the host QueryClientProvider → "No QueryClient set" when mounted in-shell (2026-10-23 lesson).
        '@tanstack/react-query': { singleton: true, requiredVersion: false, eager: true },
      },
    }),
  ],
  experiments: {
    css: true,
  },
  devServer: {
    port: Number(process.env.REMOTE_${ctx.scream}_PORT || ${ctx.port}),
    headers: { 'Access-Control-Allow-Origin': '*' },
    hot: true,
    // DEV-ONLY proxy (the tasks pattern): dev with API_BASE_URL='' goes through this proxy.
    proxy: [
      {
        context: ['/api'],
        target: \`http://localhost:\${process.env.NODE_SVC_PORT || 3001}\`,
      },
    ],
  },
};
`;
}

