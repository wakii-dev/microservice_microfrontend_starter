#!/usr/bin/env node
// gen-feature.mjs — `pnpm gen:feature <name> --app <app>`
// Adds a feature to an existing FE app: Page (Card+Table scaffold) + api module
// (decodes the error envelope) + a smoke test, then REGISTERS it by app kind:
//  - remote (rspack.config.mjs, NO router — app/remotes/*, gen-app --remote):
//    inserts the exposes entry into rspack.config.mjs.
//  - host (rspack + router — MF host như shell): inserts the LOCAL Route at the
//    GEN:routes marker (fallback: before the catch-all path="*") + the Page
//    import + the NAV_ITEMS item in src/components/NavBar.tsx (pattern HomePage —
//    the host renders its own pages, it never consumes its own exposes; R5 2026-10-28).
//  - spa (router, no rspack — admin): Route + import; menu item left as a
//    next_step (layout GEN:menu marker — app-specific).
// Uncertain anchor → writes the files + next_steps with manual instructions (no
// guessing); `modified` chỉ ghi file THẬT SỰ đã sửa.
// Output contract for AI: --json → {created, removed, modified, next_steps}.
import path from 'node:path';
import { appendImport, insertAppRoute, insertNavItem, insertRspackExpose } from './lib/docinsert.mjs';
import { exists, isDir, readText, writeNew, writeText } from './lib/io.mjs';
import { camel, parseArgs, pascal, requireValidName } from './lib/naming.mjs';
import { emit, emitError, helpText, GenResult } from './lib/result.mjs';
import { featureFiles, featureMd } from './tpl/feature.mjs';

const HELP = helpText({
  usage: 'usage: pnpm gen:feature <name> --app <app> [--root <dir>] [--json] [--help]',
  summary:
    'Add a feature to an existing FE app: Page + api module + smoke test + registration.' +
    ' Kind is auto-detected: host (rspack + router — shell) gets a local Route + NavBar item,' +
    ' spa (router only — admin) a Route, remote (rspack, no router — remotes/*) an exposes entry.' +
    ' --app takes a directory under app/ (shell, admin, remotes/tasks, an app generated by gen-app) or a relative path.',
  flags: [
    '<name>          feature/route name in kebab-case, e.g. invoices (required, first positional)',
    '--app <app>     target app (required): "shell" | "admin" | "remotes/tasks" | path',
    '--root <dir>    repo root (default: cwd)',
    '--json          output JSON {created, removed, modified, next_steps} — AI contract',
    '--help          this page',
  ],
  examples: ['pnpm gen:feature invoices --app admin', 'pnpm gen:feature reports --app shell', 'pnpm gen:feature summary --app remotes/tasks'],
  refs: [
    'docs/adr/0002 (MF) · platform/conventions/04-error-envelope.md (FE decodes via the helper — the generated api module already follows the shape)',
  ],
});

export function parseAndValidate(argv) {
  const { flags, positionals } = parseArgs(argv);
  if (flags.help) return { help: true };
  const name = positionals[0];
  if (!name) return { help: true };
  if (!flags.app) throw new Error('missing --app <app> — e.g.: pnpm gen:feature invoices --app admin');
  requireValidName(name, 'feature name');
  return { help: false, name, app: String(flags.app), root: flags.root ?? process.cwd(), json: flags.json === true };
}

export function runGenFeature(opts) {
  const { name, app } = opts;
  const root = opts.root;
  const res = new GenResult();

  // resolve the app dir: prefer app/<value>, fall back to the value as a path
  let appDir = path.join(root, 'app', app);
  if (!isDir(appDir)) {
    appDir = path.isAbsolute(app) ? app : path.join(root, app);
  }
  if (!isDir(appDir) || !exists(path.join(appDir, 'package.json'))) {
    throw new Error(`app "${app}" not found (${path.relative(root, appDir)} needs a package.json) — --app takes a name under app/ or a path`);
  }

  const hasRspack = exists(path.join(appDir, 'rspack.config.mjs'));
  const routerPath = path.join(appDir, 'src/App.tsx');
  const hasRouter = exists(routerPath);
  if (!hasRspack && !hasRouter) {
    throw new Error('the app has no src/App.tsx and no rspack.config.mjs — cannot determine the registration kind');
  }
  // remote = MF app exposing pages (no router of its own); host = MF host WITH a
  // router (shell) — renders its own pages via local routes, KHÔNG exposes (R5
  // 2026-10-28: shell từng bị xếp nhầm remote → expose module không ai consume).
  const isRemote = hasRspack && !hasRouter;
  const kind = isRemote ? 'remote' : hasRspack ? 'host' : 'spa';

  const componentName = pascal(name) + 'Page';
  const ctx = {
    name,
    camel: camel(name),
    pascal: componentName,
    kind,
    pkg: safePkgName(appDir),
    date: new Date().toISOString().slice(0, 10),
  };

  // guards: Page/api/test must not exist; the route must not exist
  for (const rel of [`src/pages/${componentName}.tsx`, `src/api/${name}.ts`, `src/pages/${componentName}.test.tsx`]) {
    if (exists(path.join(appDir, rel))) throw new Error(`${path.relative(root, path.join(appDir, rel))} already exists — idempotent-guard`);
  }
  const routePath = '/' + name;
  let routerText = null;
  if (!isRemote) {
    routerText = readText(routerPath);
    if (routerText.includes(`path="${routePath}"`)) throw new Error(`route "${routePath}" already exists in src/App.tsx`);
  }

  // --- feature files --- (FEATURE.md viết SAU registration — phản ánh đúng cái đã làm)
  for (const [rel, content] of Object.entries(featureFiles(ctx))) {
    res.createdFile(path.relative(root, writeNew(path.join(appDir, rel), content)));
  }
  ctx.registered = false;
  ctx.navRegistered = false;

  // --- register the route/expose ---
  const pkgName = safePkgName(appDir);
  if (isRemote) {
    const cfgPath = path.join(appDir, 'rspack.config.mjs');
    const cfgText = readText(cfgPath);
    const exposedModule = './' + componentName;
    const next = insertRspackExpose(cfgText, { exposedModule, file: `./src/pages/${componentName}.tsx` });
    if (next != null) {
      writeText(cfgPath, next);
      res.modifiedFile(path.relative(root, cfgPath));
      ctx.registered = true;
      res.next(
        `verify: pnpm --filter ${pkgName} test  # the generated Page + smoke test`,
        `edit: the '${exposedModule}' expose was inserted — if the page needs its own data, add the async boundary/proxy per the app/remotes/tasks pattern`,
        `edit: app/shell — remote slot: Route path "${routePath}" + RemoteSlot (remote name + exposedModule '${exposedModule}') + NavBar item (conventions/08)`,
      );
    } else {
      res.next(`edit: ${path.relative(root, cfgPath)} — add exposes '${exposedModule}': './src/pages/${componentName}.tsx' (exposes: { anchor not found)`);
    }
  } else {
    // import style: does the router file use the .js suffix (admin) or not (shell)?
    const suffix = /\.js'/.test(routerText) ? '.js' : '';
    const importLine = `import { ${componentName} } from './pages/${componentName}${suffix}';`;
    const next = insertAppRoute(routerText, { routePath, componentName, importLine });
    if (next != null) {
      writeText(routerPath, next);
      res.modifiedFile(path.relative(root, routerPath));
      ctx.registered = true;
      res.next(`verify: pnpm --filter ${pkgName} test  # the route + Page mount`);
      // host (shell): NavBar wiring luôn — host render page của chính nó (pattern
      // HomePage); spa (admin): menu theo GEN:menu marker của layout — để next_step.
      const navPath = path.join(appDir, 'src', 'components', 'NavBar.tsx');
      if (kind === 'host' && exists(navPath)) {
        const navText = readText(navPath);
        const navNext = insertNavItem(navText, { to: routePath, label: navLabel(name) });
        if (navNext != null) {
          writeText(navPath, navNext);
          res.modifiedFile(path.relative(root, navPath));
          ctx.navRegistered = true;
        } else {
          res.next(`edit: ${path.relative(root, navPath)} — add the nav item for ${routePath} (NAV_ITEMS anchor not found)`);
        }
      } else {
        res.next(`edit: the app menu/nav — add the item for ${routePath} (SPA: GEN:menu marker in the layout; shell: NavBar)`);
      }
    } else {
      res.next(
        `edit: ${path.relative(root, routerPath)} — add the import ${importLine}`,
        `edit: ${path.relative(root, routerPath)} — add <Route path="${routePath}" element={<${componentName} />} /> before the catch-all`,
      );
    }
  }
  // FEATURE.md sau registration — ctx.registered/navRegistered phản ánh đúng thực tế
  res.createdFile(path.relative(root, writeNew(path.join(appDir, 'FEATURE.md'), featureMd(ctx))));
  res.next(`read: ${path.relative(root, path.join(appDir, 'FEATURE.md'))} — the follow-up work for this feature`);
  return res;
}

/** Package name của app (để next_step verify đúng `pnpm --filter <name>`); lỗi đọc → placeholder. */
function safePkgName(appDir) {
  try {
    return JSON.parse(readText(path.join(appDir, 'package.json'))).name ?? '<app-package-name>';
  } catch {
    return '<app-package-name>';
  }
}

/** 'hello-r5' → 'Hello R5' — label cho NAV_ITEMS. */
export function navLabel(name) {
  return name
    .split('-')
    .map((part) => (part ? part[0].toUpperCase() + part.slice(1) : part))
    .join(' ');
}

// --- CLI entry ---
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.length === 0) {
  process.stdout.write(HELP + '\n');
  process.exit(0);
}
try {
  const opts = parseAndValidate(argv);
  if (opts.help) {
    process.stdout.write(HELP + '\n');
    process.exit(0);
  }
  emit(runGenFeature(opts), { json: opts.json });
} catch (err) {
  emitError(err, { json: argv.includes('--json') });
  process.exit(1);
}
